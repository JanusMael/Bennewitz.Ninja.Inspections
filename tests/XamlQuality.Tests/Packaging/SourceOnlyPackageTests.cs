using System.Diagnostics;
using System.IO.Compression;
using System.Reflection;
using System.Runtime.Versioning;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using Bennewitz.Ninja.XamlQuality;

namespace XamlQuality.Tests.Packaging;

/// <summary>
/// Every project under <c>src</c> that declares itself source-only, packed as a release packs it, and its
/// package held to what <c>plans/00003</c> says one is: the project's files as compile content and the
/// README, one dependency, on the library at a minimum of the package's own version, and files that
/// compile in any project that adopts them.
/// </summary>
/// <remarks>
/// <para>
/// ⛔ <b>This is what lets <see cref="AssemblyQualityTests"/> leave such a project out.</b> A source-only
/// project ships no assembly, so there is nothing of it to scan; what it ships instead is held here, so
/// the exemption cannot hide a shipped assembly.
/// </para>
/// <para>
/// ⚠ <b>Packed without a build, into a folder of its own.</b> The release builds at its version, runs
/// these tests, and then packs without a build, so a pack that built here would rebuild the library at
/// another version in between. A pack without a build restores nothing either:
/// <c>XamlQuality.Tests.csproj</c> references each such project with <c>ReferenceOutputAssembly</c>
/// false, which restores and builds it wherever the tests are built.
/// </para>
/// <para>
/// ⓘ <b>The files are read as text, from the package.</b> The only compile of them in this repository is
/// a test project, which references a test framework, so a stray <c>using</c> of one would pass there.
/// </para>
/// </remarks>
public sealed class SourceOnlyPackageTests : IClassFixture<SourceOnlyPackageTests.Packed>
{
    /// <summary>The version each project is packed at, as the release passes its own.</summary>
    private const string Version = "0.0.0-source-only";

    /// <summary>The library's package, the one dependency a source-only package may take.</summary>
    private const string LibraryPackage = "Bennewitz.Ninja.XamlQuality";

    /// <summary>The first line of every file, which tells analyzers to skip generated code.</summary>
    private const string Header = "// <auto-generated/>";

    /// <summary>The first line after the header's comments: generated code has no nullable context otherwise.</summary>
    private const string NullableLine = "#nullable enable";

    /// <summary>What a file may not name, matched as whole words in any case.</summary>
    private static readonly string[] TestFrameworks =
    [
        "Xunit", "NUnit", "MSTest", "TUnit",
        "Microsoft.Testing", "Microsoft.VisualStudio.TestPlatform", "Microsoft.VisualStudio.TestTools",
    ];

    /// <summary>
    /// A using directive: an alias, or a namespace or a type, global or static or neither. A using
    /// statement or declaration, <c>using (</c> or <c>using var x =</c>, does not match.
    /// </summary>
    private static readonly Regex UsingDirective = new(
        @"^[ \t]*(?:global[ \t]+)?using[ \t]+(?:@?\w+[ \t]*=[^;]*|(?:static[ \t]+)?[\w.:]+(?:<[^;]*>)?[ \t]*);",
        RegexOptions.Multiline | RegexOptions.CultureInvariant);

    /// <summary>A type declared public, after any attributes on its line.</summary>
    private static readonly Regex PublicType = new(
        @"^[ \t]*(?:\[[^\]\r\n]*\][ \t]*)*public[ \t]+(?:(?:static|sealed|abstract|partial|readonly|ref|unsafe|new)[ \t]+)*(?:class|struct|interface|enum|record|delegate)\b",
        RegexOptions.Multiline | RegexOptions.CultureInvariant);

    private readonly Packed _packed;

    public SourceOnlyPackageTests(Packed packed) => _packed = packed;

    [Fact]
    public void A_source_only_project_is_found()
    {
        // ⓘ Without one, every test below holds of nothing, and AssemblyQualityTests leaves out nothing.
        Assert.NotEmpty(_packed.Projects);
    }

    [Fact]
    public void Each_packs_without_a_build()
    {
        foreach (PackedProject project in _packed.Projects)
        {
            Assert.True(project.Exit == 0 && project.Package is not null,
                $"{project.Name} did not pack without a build (exit {project.Exit}). A pack without a build "
                + "restores nothing: XamlQuality.Tests.csproj references each source-only project with "
                + $"ReferenceOutputAssembly false, so that building the tests restores and builds it.{Environment.NewLine}{project.Output}");
        }
    }

    [Fact]
    public void The_package_holds_the_projects_files_as_compile_content_and_the_README_and_nothing_else()
    {
        foreach (PackedProject project in _packed.Projects)
        {
            using ZipArchive archive = ZipFile.OpenRead(PackageOf(project));
            string id = PackageIdOf(project.Path);
            string folder = $"cs/{LibraryFramework()}/{id}/";
            string[] files = SourceFiles(project.Path);

            string[] expected = [.. files.Select(file => "contentFiles/" + folder + file).Append("README.md").Order(StringComparer.Ordinal)];
            string[] held = [.. archive.Entries.Select(entry => entry.FullName).Where(name => !IsPackagePart(name, id)).Order(StringComparer.Ordinal)];
            Assert.Equal(expected, held);

            XDocument document = Nuspec(archive, id);
            XNamespace nuspec = document.Root!.Name.Namespace;
            (string? Include, string? BuildAction)[] compiled = [.. files.Select(file => ((string?)(folder + file), (string?)"Compile"))];
            (string? Include, string? BuildAction)[] declared =
            [
                .. document.Descendants(nuspec + "contentFiles").Elements(nuspec + "files")
                    .Select(entry => ((string?)entry.Attribute("include"), (string?)entry.Attribute("buildAction")))
                    .OrderBy(entry => entry.Item1, StringComparer.Ordinal),
            ];
            Assert.Equal(compiled, declared);

            Assert.Equal(File.ReadAllBytes(Path.Combine(RepoRoot(), "README.md")), BytesOf(archive, "README.md"));
        }
    }

    [Fact]
    public void The_package_depends_only_on_the_library_at_a_minimum_of_its_own_version()
    {
        foreach (PackedProject project in _packed.Projects)
        {
            using ZipArchive archive = ZipFile.OpenRead(PackageOf(project));
            XDocument document = Nuspec(archive, PackageIdOf(project.Path));
            XNamespace nuspec = document.Root!.Name.Namespace;
            XElement metadata = document.Root.Element(nuspec + "metadata")
                ?? throw new InvalidOperationException($"{project.Name}'s nuspec has no metadata.");

            Assert.Equal(Version, (string?)metadata.Element(nuspec + "version"));

            string[] groups = [.. metadata.Elements(nuspec + "dependencies").Elements(nuspec + "group").Select(group => group.Attribute("targetFramework")?.Value ?? "")];
            Assert.Equal([LibraryFramework()], groups);

            // A bare version in a nuspec is a minimum, which is how a project reference packs.
            (string? Id, string? Version)[] dependencies =
                [.. metadata.Descendants(nuspec + "dependency").Select(dependency => ((string?)dependency.Attribute("id"), (string?)dependency.Attribute("version")))];
            Assert.Equal([(LibraryPackage, Version)], dependencies);
        }
    }

    [Fact]
    public void The_package_is_no_development_dependency()
    {
        foreach (PackedProject project in _packed.Projects)
        {
            using ZipArchive archive = ZipFile.OpenRead(PackageOf(project));
            XDocument document = Nuspec(archive, PackageIdOf(project.Path));
            XNamespace nuspec = document.Root!.Name.Namespace;

            // ⓘ As one, `dotnet add package` leaves the library's compile assets out of the adopting
            // project, and the files do not compile (CS0103, measured for plans/00003).
            Assert.DoesNotContain(document.Descendants(nuspec + "developmentDependency"),
                element => !string.Equals(element.Value.Trim(), "false", StringComparison.OrdinalIgnoreCase));
        }
    }

    [Fact]
    public void Every_file_starts_with_its_header_and_then_turns_nullable_on()
    {
        AssertEveryFile(text =>
        {
            string[] lines = text.ReplaceLineEndings("\n").Split('\n');
            string? code = lines.Skip(1).FirstOrDefault(line => line.Trim().Length > 0 && !line.TrimStart().StartsWith("//", StringComparison.Ordinal));
            return lines[0] == Header && code == NullableLine
                ? null
                : $"does not start with \"{Header}\" and then \"{NullableLine}\"";
        });
    }

    [Fact]
    public void No_file_has_a_using_directive()
    {
        // ⓘ Every type is written from global::, so that no global using or alias of the adopting
        // project's can take a name the file uses.
        AssertEveryFile(text => UsingDirective.Match(text) is { Success: true } match ? $"has \"{match.Value.Trim()}\"" : null);
    }

    [Fact]
    public void No_file_declares_a_public_type()
    {
        AssertEveryFile(text => PublicType.Match(text) is { Success: true } match ? $"declares \"{match.Value.Trim()}\"" : null);
    }

    [Fact]
    public void No_file_names_a_test_framework()
    {
        // ⓘ A check reports and never asserts: the adopting project chooses the runner.
        AssertEveryFile(text =>
            TestFrameworks.FirstOrDefault(name => Regex.IsMatch(text, @"\b" + Regex.Escape(name) + @"\b", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant))
                is string named
                ? $"names {named}"
                : null);
    }

    /// <summary>
    /// Whether a project declares itself source-only: its package holds its files as source and no
    /// assembly, so <see cref="AssemblyQualityTests"/> leaves it out and this class holds its package.
    /// </summary>
    internal static bool DeclaresSourceOnly(string projectPath) =>
        XDocument.Load(projectPath)
            .Descendants("SourceOnlyPackage")
            .Any(element => string.Equals(element.Value.Trim(), "true", StringComparison.OrdinalIgnoreCase));

    /// <summary>Fails naming every file, in every package, that <paramref name="violation"/> says breaks a rule.</summary>
    private void AssertEveryFile(Func<string, string?> violation)
    {
        List<string> found = [];
        int read = 0;
        foreach (PackedProject project in _packed.Projects)
        {
            using ZipArchive archive = ZipFile.OpenRead(PackageOf(project));
            foreach (ZipArchiveEntry entry in archive.Entries.Where(entry => entry.FullName.EndsWith(".cs", StringComparison.Ordinal)))
            {
                read++;
                using StreamReader reader = new(entry.Open(), Encoding.UTF8);
                if (violation(reader.ReadToEnd()) is string said)
                {
                    found.Add($"{project.Name}: {entry.FullName} {said}");
                }
            }
        }

        Assert.True(read > 0, "No package held a .cs file, so no file was checked.");
        Assert.True(found.Count == 0, string.Join(Environment.NewLine, found));
    }

    private static string PackageOf(PackedProject project) =>
        project.Package ?? throw new InvalidOperationException($"{project.Name} did not pack; Each_packs_without_a_build says why.");

    private static XDocument Nuspec(ZipArchive archive, string id)
    {
        using Stream stream = archive.GetEntry(id + ".nuspec")?.Open()
            ?? throw new InvalidOperationException($"The package holds no {id}.nuspec.");
        return XDocument.Load(stream);
    }

    private static byte[] BytesOf(ZipArchive archive, string name)
    {
        using Stream stream = archive.GetEntry(name)?.Open() ?? throw new InvalidOperationException($"The package holds no {name}.");
        using MemoryStream bytes = new();
        stream.CopyTo(bytes);
        return bytes.ToArray();
    }

    /// <summary>What every package holds beside its content: its manifest, and the parts of the zip format NuGet writes.</summary>
    private static bool IsPackagePart(string name, string id) =>
        name == id + ".nuspec"
        || name == "[Content_Types].xml"
        || name.StartsWith("_rels/", StringComparison.Ordinal)
        || name.StartsWith("package/services/metadata/core-properties/", StringComparison.Ordinal);

    /// <summary>Every <c>.cs</c> file in the project's folder, by its path below it, written with <c>/</c>.</summary>
    private static string[] SourceFiles(string projectPath)
    {
        string folder = Path.GetDirectoryName(projectPath)!;
        return
        [
            .. Directory.GetFiles(folder, "*.cs", SearchOption.AllDirectories)
                .Select(file => Path.GetRelativePath(folder, file).Replace('\\', '/'))
                .Where(file => file.Split('/')[0] is not ("bin" or "obj"))
                .Order(StringComparer.Ordinal),
        ];
    }

    private static string PackageIdOf(string projectPath) =>
        XDocument.Load(projectPath).Descendants("PackageId").Select(element => element.Value.Trim()).FirstOrDefault(value => value.Length > 0)
        ?? Path.GetFileNameWithoutExtension(projectPath);

    /// <summary>The framework the library targets, as a package names it: <c>net10.0</c>.</summary>
    private static string LibraryFramework()
    {
        FrameworkName framework = new(typeof(XamlScanContext).Assembly.GetCustomAttribute<TargetFrameworkAttribute>()!.FrameworkName);
        return "net" + framework.Version.ToString(2);
    }

    /// <summary>
    /// Walks up from the test assembly to the directory holding the solution, so the tests do not
    /// depend on the working directory a runner happens to choose.
    /// </summary>
    private static string RepoRoot()
    {
        DirectoryInfo? directory = new(AppContext.BaseDirectory);

        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "XamlQuality.slnx")))
        {
            directory = directory.Parent;
        }

        Assert.NotNull(directory);
        return directory.FullName;
    }

    /// <summary>A source-only project, what its pack printed, and the package it made, if it made one.</summary>
    public sealed record PackedProject(string Path, int Exit, string Output, string? Package)
    {
        /// <summary>The project's file name, without its extension.</summary>
        public string Name => System.IO.Path.GetFileNameWithoutExtension(Path);
    }

    /// <summary>
    /// Each source-only project under <c>src</c>, packed once for the class into a folder of its own,
    /// which is removed afterwards.
    /// </summary>
    public sealed class Packed : IDisposable
    {
        private static readonly TimeSpan PackTimeout = TimeSpan.FromMinutes(5);

        private readonly string _folder = Directory.CreateTempSubdirectory("xq-source-only-").FullName;

        public Packed()
        {
            Projects =
            [
                .. Directory.GetFiles(Path.Combine(RepoRoot(), "src"), "*.csproj", SearchOption.AllDirectories)
                    .Where(DeclaresSourceOnly)
                    .Order(StringComparer.Ordinal)
                    .Select(project => Pack(project, Path.Combine(_folder, Path.GetFileNameWithoutExtension(project)))),
            ];
        }

        /// <summary>Each source-only project, packed.</summary>
        public IReadOnlyList<PackedProject> Projects { get; }

        public void Dispose() => Directory.Delete(_folder, recursive: true);

        /// <summary>
        /// Packs <paramref name="project"/> without a build, in the configuration these tests were built
        /// in, and with no build server left behind.
        /// </summary>
        private static PackedProject Pack(string project, string output)
        {
            string configuration = typeof(SourceOnlyPackageTests).Assembly.GetCustomAttribute<AssemblyConfigurationAttribute>()?.Configuration
                ?? throw new InvalidOperationException("The test assembly names no configuration to pack in.");

            ProcessStartInfo start = new("dotnet")
            {
                WorkingDirectory = RepoRoot(),
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                StandardOutputEncoding = Encoding.UTF8,
                StandardErrorEncoding = Encoding.UTF8,
            };
            foreach (string argument in (string[])["pack", project, "-c", configuration, "--no-build", "--nologo", "--disable-build-servers", "-p:Version=" + Version, "--output", output])
            {
                start.ArgumentList.Add(argument);
            }

            start.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
            start.Environment["DOTNET_NOLOGO"] = "1";
            start.Environment["DOTNET_SKIP_FIRST_TIME_EXPERIENCE"] = "1";

            using Process process = Process.Start(start)!;
            Task<string> printed = process.StandardOutput.ReadToEndAsync();
            Task<string> errors = process.StandardError.ReadToEndAsync();
            if (!process.WaitForExit(PackTimeout))
            {
                process.Kill(entireProcessTree: true);
                process.WaitForExit();
                return new(project, -1, $"Stopped after {PackTimeout}.{Environment.NewLine}{printed.Result}{errors.Result}", null);
            }

            // The second wait lets the redirected streams drain.
            process.WaitForExit();
            string[] packages = Directory.Exists(output) ? Directory.GetFiles(output, "*.nupkg") : [];
            return new(project, process.ExitCode, printed.Result + errors.Result, packages.Length == 1 ? packages[0] : null);
        }
    }
}
